"""Run the complete pipeline on every faulty sample repository and report metrics.

Usage:
    python run_evaluation.py [--samples sample-repos] [--out docs]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from evaluation.framework import evaluate_all
from orchestration.pipeline import AnalysisOrchestrator
from storage.database import get_db


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--samples", default=str(Path(__file__).parent / "sample-repos"))
    parser.add_argument("--out", default=str(Path(__file__).parent / "docs"))
    parser.add_argument("--timeout", type=int, default=180)
    args = parser.parse_args()

    samples = Path(args.samples)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    examples = out / "examples"
    examples.mkdir(exist_ok=True)

    db = get_db()
    orchestrator = AnalysisOrchestrator(db=db)
    for expected_file in sorted(samples.glob("*/expected_rca.json")):
        repo = expected_file.parent
        print(f"\n=== Analysing {repo.name} ===", flush=True)
        run = orchestrator.start(str(repo), repo.name)
        finished = orchestrator.wait(run.id, timeout=args.timeout)
        summary = (finished.summary if finished else {})
        print(json.dumps({
            "id": run.id,
            "status": finished.status.value if finished else "TIMEOUT",
            "assessment": summary.get("assessment"),
            "findings": summary.get("total_issues"),
            "tests": summary.get("total_tests"),
            "failed_tests": summary.get("failed_tests"),
            "root_causes": summary.get("root_causes"),
            "agent": summary.get("agent"),
        }, indent=2), flush=True)
        report = db.get_report(run.id, "markdown")
        if report:
            (examples / f"{repo.name}-report.md").write_text(report, encoding="utf-8")

    metrics = evaluate_all(samples, db=db)
    (out / "evaluation_results.json").write_text(
        json.dumps(metrics, indent=2), encoding="utf-8"
    )
    lines = [
        "# Evaluation Results",
        "",
        f"Repositories evaluated: **{metrics['repositories']}**",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Mean detection precision (contextual) | {metrics['mean_detection_precision']} |",
        f"| Mean detection precision (strict root category only) | {metrics['mean_strict_detection_precision']} |",
        f"| Mean detection recall | {metrics['mean_detection_recall']} |",
        f"| Mean detection F1 | {metrics['mean_detection_f1']} |",
        f"| Root-cause identification rate | {metrics['root_cause_identification_rate']} |",
        f"| Mean cascade accuracy | {metrics['mean_cascade_accuracy']} |",
        f"| Mean fix verification rate | {metrics['mean_fix_verification_rate']} |",
        f"| Mean evidence consistency | {metrics['mean_evidence_consistency']} |",
        f"| Total incorrect/rejected hypotheses | {metrics['total_incorrect_hypotheses']} |",
        "",
        "## Per repository",
        "",
        "| Repository | Precision | Recall | F1 | Root cause | Cascade | Verified fixes |",
        "|---|---:|---:|---:|---|---:|---:|",
    ]
    for item in metrics["per_repository"]:
        lines.append(
            f"| {item['repository']} | {item['detection_precision']} | "
            f"{item['detection_recall']} | {item['detection_f1']} | "
            f"{'yes' if item['root_cause_identified'] else 'no'} | "
            f"{item['cascade_accuracy']} | {item['fix_verification_rate']} |"
        )
    lines.extend(["", "Generated by `python run_evaluation.py`.", ""])
    (out / "EVALUATION.md").write_text("\n".join(lines), encoding="utf-8")
    print("\nEvaluation written to", out / "EVALUATION.md")


if __name__ == "__main__":
    main()
